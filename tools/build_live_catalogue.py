"""Generate the visual catalogue from the dated live-seva asset manifest."""
from pathlib import Path
from html import escape
import argparse
import json

ROOT=Path(__file__).resolve().parents[1]
MANIFEST='references/live-sevas/2026-11-13/manifest.json'


def render():
    data=json.loads((ROOT/MANIFEST).read_text())
    cards=[]
    for item in data['offerings']:
        e=lambda key:escape(str(item[key]),quote=True)
        first=f'₹{item["first_amount_minor"]//100}'
        regular=f'₹{item["regular_amount_minor"]//100}'
        package=escape(item['package_id'] or 'Not yet verified in this observation')
        cards.append(f'''<article class="seva-card" data-product-id="{e('product_id')}">
          <img class="seva-hero" src="../{e('hero_image')}" alt="{e('display_name')} — actual live offering artwork" />
          <div class="seva-content"><p class="eyebrow">Every {e('weekday')} · Weekly</p><h2>{e('display_name')}</h2><p class="temple-name">{e('temple')}</p>
          <div class="price-reference"><p><strong>{first}</strong> first seva</p><p>Then <b>{regular} per seva</b> · weekly</p></div>
          <h3>{e('package_name')}</h3><p>{e('summary')}</p>
          <figure class="temple-reference"><img src="../{e('temple_image')}" alt="Temple reference from the live {e('display_name')} page" loading="lazy" /><figcaption>Temple photo used on the live offering page</figcaption></figure>
          <details class="source-details"><summary>Identity and source reference</summary><dl><dt>Product ID</dt><dd>{e('product_id')}</dd><dt>Package ID</dt><dd>{package}</dd><dt>Live page title</dt><dd>{e('live_heading')}</dd></dl></details>
          <a class="live-link" href="{e('source_url')}" target="_blank" rel="noopener">View the live offering ↗</a></div></article>''')
    return '<!-- Generated by tools/build_live_catalogue.py; edit the manifest/template. -->\n'+(ROOT/'catalogue/page.html.template').read_text().replace('{{OFFERING_CARDS}}','\n'.join(cards))


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    target=ROOT/'catalogue/index.html';expected=render()
    if args.check:
        assert target.is_file() and target.read_text()==expected,'Live catalogue is stale; run python3 tools/build_live_catalogue.py'
        print('PASS: visual live catalogue matches dated product and asset observations')
    else:
        target.write_text(expected)
        print('Built the visual catalogue for the three launched sevas')
