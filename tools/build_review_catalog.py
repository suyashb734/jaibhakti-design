"""Build a file:// compatible walkthrough catalogue from the design registries."""
from pathlib import Path
import argparse
import json

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'walkthroughs/assets/catalog.generated.js'


def catalogue():
    records=json.loads((ROOT/'registries/screens.json').read_text())['screens']
    screens={item['id']:item for item in records if item['platform'] in {'reference','app'}}
    tours=json.loads((ROOT/'registries/walkthroughs.json').read_text())['tours']
    ids=[tour['id'] for tour in tours]
    assert len(ids)==len(set(ids)),'Duplicate tour ID'
    for tour in tours:
        assert (ROOT/tour['context']).is_file(),tour['context']
        assert tour['steps'],tour['id']
        for step in tour['steps']:
            assert step['screen_id'] in screens,step['screen_id']
    tours.append({'id':'all-app','title':'All registered design states','status':'Draft · full inventory','summary':'Browse every registered app draft state, including loading, empty, error, partial-media and long-content examples. Frozen captures are historical reference images.','context':'previews/mobile/README.md','steps':[{'screen_id':item['id'],'label':item['title'],'note':'Review this sample state and its related rules. Use the source registry and change package for scope and approval status.'} for item in records if item['platform']=='app']})
    return {'screens':screens,'tours':tours}


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    text='// Generated by tools/build_review_catalog.py; edit registries, not this file.\nwindow.JB_REVIEW_CATALOG = '+json.dumps(catalogue(),ensure_ascii=False,indent=2)+';\n'
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text()!=text:
            raise SystemExit('Walkthrough catalogue is stale. Run python3 tools/build_review_catalog.py')
        print('PASS: walkthrough catalogue matches source screen and tour registries')
    else:
        OUTPUT.parent.mkdir(parents=True,exist_ok=True)
        OUTPUT.write_text(text)
        print('Built walkthrough catalogue from registered screens and tours')


if __name__=='__main__':main()
